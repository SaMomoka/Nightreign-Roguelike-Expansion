"""Launch only generated packages against explicitly configured isolated saves."""
import csv
import hashlib
import json
import re
import shutil
import subprocess
from pathlib import Path
from relic_presets import ROOT, load


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest().upper()


def verify_package(folder,root=ROOT):
    root=Path(root).resolve();folder=Path(folder).resolve()
    if not folder.is_relative_to(root/"local/packages"):
        raise ValueError("只能启动项目local/packages中的生成包")
    metadata=load(folder/"package.json")
    if metadata.get("schema_version")!=1:
        raise ValueError("实验包格式不支持")
    name=metadata.get("savefile","")
    if not re.fullmatch(r"NRE_[A-Za-z0-9_]+\.sl2",name):
        raise ValueError("实验包必须使用独立NRE存档名")
    kind=metadata.get("kind","relic")
    required={"generate.me3","play.me3","mod/regulation.bin","manifest.json"}
    if kind in ("combined","native_menu"):
        required.update({"rollback.me3","reward-mod/regulation.bin","mod/build-report.json",
                         "inputs/relic.bin","inputs/rewards.bin",
                         "inputs/relic-manifest.json","inputs/rewards-manifest.json"})
    if kind in ("native_menu","relic_editor","full_relic_editor"):
        required.update({"mod/script/talk/m10_00_00_00.talkesdbnd.dcx",
                         "mod/msg/zhocn/menu_dlc01.msgbnd.dcx","mod/msg/engus/menu_dlc01.msgbnd.dcx"})
    if kind=="native_menu":
        required.update({"menu-spec.json","native-menu-report.json"})
    if kind=="relic_editor":
        required.update({"editor-plan.json","mod/editor-report.json","reward-base.bin"})
    if kind=="full_relic_editor":
        required.update({"full-menu-plan.json","runtime-catalog.json","runtime-layout.json","full-build-report.json"})
        tools={"relic_runtime.py","relic_selection.py","full_relic_menu.py","probe_relic_params.py","probe_relic_work_values.py","relic_filters.py"}
        required.update({f"mod/msg/{lang}/item_dlc01.msgbnd.dcx" for lang in ('zhocn','engus')})
        tool_hashes=metadata.get("tool_hashes",{})
        if set(tool_hashes)!=tools or any(sha(root/"tools"/name)!=tool_hashes[name] for name in tools):
            raise ValueError("运行时模块已变化，需要重新构建完整包")
    hashes=metadata.get("sha256",{})
    if not required.issubset(hashes):
        raise ValueError("实验包缺少完整性清单")
    for relative,expected in hashes.items():
        path=(folder/relative).resolve()
        if not path.is_relative_to(folder) or sha(path)!=expected:
            raise ValueError("实验包文件已变化："+relative)
    # Packages are generated by our builder. Exact profile validation prevents
    # an edited metadata file from silently redirecting to the formal save.
    common=f'profileVersion = "v1"\nsavefile = "{name}"\nstart_online = false\n[[supports]]\ngame = "nightreign"\n'
    package_ids={"relic":"NRE-Relic-Generation","native_rewards":"NRE-Native-Rewards",
                 "combined":"NRE-Combined-Generation","native_menu":"NRE-Native-Menu",
                 "relic_editor":"NRE-Relic-Editor","full_relic_editor":"NRE-Full-Relic-Editor"}
    if kind not in package_ids:
        raise ValueError("未知实验包类型")
    expected={"play.me3":common,
              "generate.me3":common+'[[packages]]\nid = "'+package_ids[kind]+'"\nsource = "./mod"\n'}
    if kind in ("relic_editor","full_relic_editor"):
        expected["play.me3"]=expected["generate.me3"]
    if kind in ("combined","native_menu"):
        expected["play.me3"]=common+'[[packages]]\nid = "NRE-Native-Rewards"\nsource = "./reward-mod"\n'
        expected["rollback.me3"]=common
        if sha(folder/"reward-mod/regulation.bin")!=sha(folder/"inputs/rewards.bin"):
            raise ValueError("整合包运行参数与原奖励包不一致")
    for file,text in expected.items():
        if (folder/file).read_text(encoding="utf-8")!=text:
            raise ValueError("启动配置不符合隔离模板")
    return metadata


def prepare_save(seed,savefile):
    seed=Path(seed).resolve()
    if not seed.name.startswith("NRE_") or seed.suffix.lower()!=".sl2":
        raise ValueError("只接受已有NRE隔离存档作为种子，不能直接使用正式存档")
    if not re.fullmatch(r"NRE_[A-Za-z0-9_]+\.sl2",savefile):
        raise ValueError("无效的隔离存档名")
    destination=seed.parent/savefile
    if destination==seed:
        raise ValueError("新实验不能覆盖种子存档")
    if not destination.exists():
        with seed.open("rb") as source,destination.open("xb") as target:
            shutil.copyfileobj(source,target)
    return destination


def launch(folder,generation,root=ROOT,rollback=False):
    root=Path(root).resolve();folder=Path(folder).resolve()
    metadata=verify_package(folder,root)
    if rollback and (metadata.get("kind") not in ("combined","native_menu") or generation):
        raise ValueError("无效的整合包回滚模式")
    runtime=load(root/"local/runtime.json")
    me3=Path(runtime["me3"])
    if not me3.is_file() or me3.name.lower()!="me3.exe":
        raise ValueError("ME3路径无效")
    installed=Path(runtime["game"])/"regulation.bin"
    manifest=load(folder/"manifest.json")
    if sha(installed)!=manifest["source_sha256"]:
        raise ValueError("游戏版本已变化；请重新导出和审核，不能加载旧生成包")
    if metadata.get("kind") in ("native_menu","relic_editor","full_relic_editor"):
        expected="BB295CFC9F6C8ADF8D7DA261A5FC98095BDF03044DDAC9E99D69621496BF2B2C"
        if manifest.get("archive_header_sha256")!=expected or sha(Path(runtime["game"])/"data0.bhd")!=expected:
            raise ValueError("游戏菜单资源版本已变化，需要重新审核原生菜单")
    result=subprocess.run(["tasklist","/FI","IMAGENAME eq nightreign.exe","/FO","CSV","/NH"],
        capture_output=True,creationflags=getattr(subprocess,"CREATE_NO_WINDOW",0))
    if result.returncode:
        raise ValueError("无法确认游戏是否已经退出")
    if b"nightreign.exe" in result.stdout.lower():
        raise ValueError("请先正常退出当前游戏，再切换配置")
    save=prepare_save(runtime["test_seed"],metadata["savefile"])
    label="rollback" if rollback else ("generate" if generation else "play")
    with (folder/(label+"-launch.log")).open("ab") as log:
        process=subprocess.Popen([str(me3),"launch","--game","nightreign","--profile",
            str(folder/(label+".me3"))],stdout=log,stderr=log,
            creationflags=getattr(subprocess,"CREATE_NO_WINDOW",0))
    return {"pid":process.pid,"savefile":save.name,"mode":label}
